# 1. 프로그램에서 사용할 전체 할 일 목록을 2차원 리스트로 만듭니다.
# 구조: [ [작업이름, 남은일수, 완료여부], [작업이름, 남은일수, 완료여부] ]
tasks = [
    ["UI 디자인", 3, "Y"],
    ["데이터베이스 설계", 7, "N"]
]

# 2. 사용자가 종료를 선택할 때까지 무한히 반복하는 메뉴판입니다.
while True:
    print("\n====== 프로젝트 일정 관리기 ======")
    print("1. 할 일 목록 보기")
    print("2. 새 할 일 추가하기")
    print("3. 할 일 완료 체크")
    print("4. 마감 임박 긴급 작업 확인")
    print("5. 프로그램 종료")
    print("=================================")
    
    # 사용자에게 원하는 메뉴 번호를 입력받습니다.
    menu = input("원하는 기능의 번호를 입력하세요: ")
    
    # 사용자가 입력한 번호에 따라 실행할 코드를 나눕니다.
    if menu == "1":
        print("\n[안내] 할 일 목록 보기 기능을 실행할 예정입니다.")
        # 나중에 여기에 목록 보기 함수를 넣을 거예요.
        
    elif menu == "2":
        print("\n[안내] 새 할 일 추가하기 기능을 실행할 예정입니다.")
        # 나중에 여기에 할 일 추가 함수를 넣을 거예요.
        
    elif menu == "3":
        print("\n[안내] 할 일 완료 체크 기능을 실행할 예정입니다.")
        # 나중에 여기에 완료 체크 함수를 넣을 거예요.
        
    elif menu == "4":
        print("\n[안내] 마감 임박 긴급 작업 확인 기능을 실행할 예정입니다.")
        # 나중에 여기에 긴급 작업 확인 함수를 넣을 거예요.
        
    elif menu == "5":
        print("\n프로그램을 종료합니다. 수고하셨습니다!")
        break  # while 반복문을 빠져나가서 프로그램을 끝냅니다.
        
    else:
        print("\n[오류] 잘못된 번호입니다. 1~5 사이의 숫자를 입력해 주세요.")